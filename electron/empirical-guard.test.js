const assert = require('assert');
const { detectUnsupportedEmpiricalClaims: audit } = require('./agent/empirical-guard');
const claim = '<p>样本为2846名，OLS回归结果显著，系数为0.25，p<0.01。[E1]</p>';
const source = '样本为2846名，OLS回归结果显著，系数为0.25，p<0.01。';
assert(audit(claim).length);
assert(audit(claim, { hasAttachments: true, hasEvidence: true, hasToolResult: true }).length, '旧布尔标记不得绕过校验');
assert(audit(claim, { attachments: [{ excerpt: '这是一份无关的工作说明。' }] }).length);
assert(audit(claim, { evidence: [{ evidenceId: 'E1', text: '样本为12名，OLS回归不显著，p>0.1。' }] }).length);
assert(audit(claim, { toolResults: [{ error: null, summary: '均值为2。' }] }).length);
assert(audit(claim, { toolResults: [{ error: '执行失败', summary: source }] }).length, '失败工具产出不能当作证据');
assert.equal(audit(claim, { evidence: [{ evidenceId: 'E1', text: source }] }).length, 0);
assert(audit(claim, { evidence: [{ evidenceId: 'E2', text: source }] }).length, '未引用的检索命中不能放行');
assert.equal(audit(claim, { toolResults: [{ error: null, summary: source }] }).length, 0);
assert.equal(audit(claim, { attachments: [{ excerpt: source }] }).length, 0);
assert(audit('<p>OLS回归结果显著，系数为0.25。</p>', { toolResults: [{ summary: 'OLS回归不显著，系数为0.25。' }] }).length);
assert(audit('<p>Logit回归结果显著，系数为0.25。</p>', { toolResults: [{ summary: 'OLS回归结果显著，系数为0.25。' }] }).length);
assert(audit('<p>系数为-0.25，p<0.05。</p>', { toolResults: [{ summary: '系数为0.25，p<0.05。' }] }).length, '数值符号必须一致');
assert(audit('<p>p<0.05。</p>', { toolResults: [{ summary: 'p>0.05。' }] }).length, '比较方向必须一致');
assert(audit('<p>均值为0.25，标准差为0.5。</p>', { toolResults: [{ summary: '均值为0.5，标准差为0.25。' }] }).length, '同样的数值不能挪用到其他指标');
assert.equal(audit('<p>均值为2。</p>', { toolResults: [{ summary: '', table: { rows: [{ 均值: 2 }] } }] }).length, 0);
assert.equal(audit('<p>计划选取100名参与者开展调查。</p>').length, 0);
assert.equal(audit('<p>本文讨论理论机制，实证结论尚待检验。</p>').length, 0);
assert.equal(audit('<p>本轮没有可用数据，无法报告样本量、回归系数、显著性水平或置信区间。</p>').length, 0, '缺失说明不是已完成的统计结果');
console.log('Empirical claims require matching cited evidence or actual source/results passed');
